using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace LayerLog.Core.Gcode;

public static partial class GcodeParser
{
    public static GcodeInfo Parse(Stream stream)
    {
        var config = new Dictionary<string, string>();
        var objects = new List<string>();
        var thumbnail = new StringBuilder();
        var bestThumbnail = "";
        string? version = null, time = null;
        DateTime generatedAt = default;
        double? grams = null;
        var inConfig = false;
        var inThumbnail = false;
        var configClosed = false;

        using var reader = new StreamReader(stream, Encoding.Latin1);
        while (reader.ReadLine() is { } line)
        {
            // Almost every line of a real gcode is a move: skip them cheaply.
            if (line.Length == 0 || line[0] != ';') continue;

            if (inThumbnail)
            {
                if (line.StartsWith("; png end"))
                {
                    inThumbnail = false;
                    if (thumbnail.Length > bestThumbnail.Length) bestThumbnail = thumbnail.ToString();
                }
                else thumbnail.Append(line.AsSpan(1).Trim());
            }
            else if (line.StartsWith("; png begin"))
            {
                inThumbnail = true;
                thumbnail.Clear();
            }
            else if (line.Contains("CONFIG_BLOCK_START")) inConfig = true;
            else if (line.Contains("CONFIG_BLOCK_END"))
            {
                inConfig = false;
                configClosed = true;
            }
            else if (inConfig)
            {
                var split = line.IndexOf(" = ", StringComparison.Ordinal);
                if (split > 2) config[line[2..split]] = line[(split + 3)..].Trim();
            }
            else if (line.StartsWith("; printing object "))
            {
                var name = ObjectName().Match(line).Groups[1].Value;
                if (name.Length > 0 && !objects.Contains(name)) objects.Add(name);
            }
            else if (GeneratedBy().Match(line) is { Success: true } g)
            {
                version = g.Groups[1].Value;
                generatedAt = DateTime.ParseExact($"{g.Groups[2].Value} {g.Groups[3].Value}", "yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture);
            }
            else if (line.StartsWith("; filament used [g] = "))
                grams = double.TryParse(line[22..], CultureInfo.InvariantCulture, out var v) ? v : null;
            else if (line.StartsWith("; estimated printing time (normal mode) = "))
                time = line[42..].Trim();
        }

        if (version is null) throw new GcodeFormatException("El fitxer no és de Creality Print.");
        if (!configClosed) throw new GcodeFormatException("El fitxer no té la configuració completa.");
        if (!config.TryGetValue("print_settings_id", out var process) || !config.TryGetValue("filament_settings_id", out var filament))
            throw new GcodeFormatException("El fitxer no indica els perfils usats.");

        process = Unquote(process);
        filament = Unquote(filament);
        var parents = config.GetValueOrDefault("inherits_group", "").Split(';');
        var parent = (int i) => i < parents.Length ? Unquote(parents[i]) : "";
        var processBase = parent(0);
        var filamentBase = parent(1);

        return new GcodeInfo(version, generatedAt, time, grams, objects, process, filament,
            processBase.Length > 0 ? processBase : process,
            filamentBase.Length > 0 ? filamentBase : filament,
            config,
            bestThumbnail.Length > 0 ? Convert.FromBase64String(bestThumbnail) : null);
    }

    static string Unquote(string value) => value.Split(';')[0].Trim().Trim('"');

    [GeneratedRegex(@"generated by Creality_Print V(\S+) on (\S+) at (\S+)")]
    private static partial Regex GeneratedBy();

    [GeneratedRegex(@"^; printing object (.+?) id:")]
    private static partial Regex ObjectName();
}
